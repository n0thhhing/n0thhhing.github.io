import assert from 'node:assert/strict';

export async function checkTerminal(page, origin, artifactDir) {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(origin);
  await page.reload();
  assert.equal(await page.locator('#breadcrumb').evaluate(n => getComputedStyle(n.closest('.editor-path')).borderBottomStyle), 'none');
  await page.locator('#terminal-input').focus();
  assert.equal(await page.locator('#terminal-new').isVisible(), true);
  assert.equal(await page.locator('#terminal-split').isVisible(), true);
  assert.equal(await page.locator('.terminal-run').count(), 0);
  await page.locator('.terminal-intro p').click();
  assert.equal(await page.locator('#terminal-input').evaluate(n => n === document.activeElement), true);
  const command = `echo ${'wrap '.repeat(120)}`;
  await page.locator('#terminal-input').fill(command);
  assert.equal(await page.locator('#terminal-input').evaluate(n => n.getBoundingClientRect().height > parseFloat(getComputedStyle(n).lineHeight) * 1.5), true, 'Long commands wrap onto further rows');
  await page.keyboard.press('Enter');
  assert.match(await page.locator('#terminal-output').innerText(), /wrap wrap/);
  await page.locator('#terminal-output .terminal-entry-output').click();
  assert.equal(await page.locator('#terminal-input').evaluate(n => n === document.activeElement), true, 'Clicking output returns typing to the prompt');
  await page.locator('#terminal-new').click();
  await page.getByRole('menuitem', { name: 'New Terminal', exact: true }).click();
  assert.equal(await page.locator('.terminal-tab').count(), 2);
  assert.equal(await page.locator('#terminal-output').innerText(), '');
  await page.locator('#terminal-input').fill('cd projects');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#terminal-cwd').textContent(), '~/projects');
  assert.equal(await page.locator('.active-terminal-pane form .prompt-path').textContent(), 'website/projects');
  await page.locator('.terminal-tab').first().click();
  assert.match(await page.locator('#terminal-output').innerText(), /wrap wrap/);
  assert.equal(await page.locator('#terminal-cwd').textContent(), '~');
  await page.locator('.terminal-tab').last().click();
  await page.locator('#terminal-split').click();
  await page.getByRole('menuitem', { name: 'Split Down', exact: true }).click();
  assert.equal(await page.locator('.terminal-pane').count(), 2);
  await page.locator('#terminal-input').fill('pwd');
  await page.keyboard.press('Enter');
  assert.match(await page.locator('#terminal-output').innerText(), /~\/projects/);
  assert.equal(await page.locator('.terminal-pane:not(.active-terminal-pane) .terminal-actions').isVisible(), false);
  const separator = page.locator('.terminal-pane-separator');
  await separator.focus();
  await page.keyboard.press('ArrowDown');
  assert.equal(await separator.getAttribute('aria-valuenow'), '55');
  await page.locator('#terminal-input').focus();
  await page.locator('#terminal-maximize').click();
  assert.equal(await page.locator('#content').isVisible(), false);
  assert.equal(await page.locator('.terminal-pane:visible').count(), 1);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#content').isVisible(), true);
  assert.equal(await page.locator('.terminal-pane:visible').count(), 2);
  await page.locator('#terminal-input').focus();
  if (artifactDir) await page.screenshot({ path: `${artifactDir}/terminal-splits.png` });
  await page.locator('.active-terminal-pane [data-close-terminal]').click();
  assert.equal(await page.locator('.terminal-pane').count(), 1);
  await page.locator('#terminal-input').focus();
  await page.keyboard.press('Control+l');
  assert.equal(await page.locator('#terminal-output').innerText(), '');
  await page.locator('#terminal-input').fill('about');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#content').getAttribute('data-route'), 'about');
  await page.setViewportSize({ width: 320, height: 568 });
  await page.locator('#terminal-input').focus();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('#terminal-input').fill('echo mobile');
  await page.keyboard.press('Enter');
  assert.match(await page.locator('#terminal-output').innerText(), /mobile/);
}
