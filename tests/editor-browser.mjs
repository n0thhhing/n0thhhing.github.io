import assert from 'node:assert/strict';
import { projects } from '../site/js/content.js';
import { themes } from '../site/js/themes.js';

export async function checkEditor(page, origin, artifactDir, contrastFailures) {
  page.setDefaultTimeout(5000);
  const quickOpen = async query => {
    await page.keyboard.press('Control+p');
    await page.locator('#file-query').fill(query);
    await page.keyboard.press('Enter');
  };
  const split = async direction => {
    await page.locator('.active-pane .content').focus();
    await page.locator('#editor-split-btn').click();
    await page.getByRole('menuitem', { name: `Split ${direction}`, exact: true }).click();
  };
  const closePane = async () => {
    await page.locator('.active-pane .content').focus();
    await page.locator('#editor-split-btn').click();
    await page.getByRole('menuitem', { name: 'Close pane', exact: true }).click();
  };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${origin}/#about`);
  await page.reload();
  if (await page.locator('#terminal').isVisible()) await page.locator('.statusbar [data-terminal-toggle]').click();
  assert.equal(await page.locator('#tabs .pane-tab').count(), 1);
  assert.equal(await page.locator('.folder-root').evaluate(n => getComputedStyle(n, '::before').content), 'none', 'Folder disclosure is carried by its icon');
  const explorerAlignment = await page.locator('.root-folder > .tree-contents').evaluate(tree => {
    const rows = [...tree.querySelectorAll(':scope > details > summary, :scope > #file-nav > a, :scope > .tree-leaf-static')];
    return rows.map(row => {
      const icon = row.querySelector('.folder-icon, .file-icon');
      const walker = document.createTreeWalker(row, NodeFilter.SHOW_TEXT);
      let text;
      while ((text = walker.nextNode())) if (text.textContent.trim() && !icon.contains(text)) break;
      const range = document.createRange();
      range.setStart(text, text.textContent.search(/\S/));
      range.setEnd(text, text.length);
      return { icon: icon.getBoundingClientRect().left, label: range.getBoundingClientRect().left };
    });
  });
  assert.equal(new Set(explorerAlignment.map(row => row.icon)).size, 1, 'Sibling folder and file icons align');
  assert.equal(new Set(explorerAlignment.map(row => row.label)).size, 1, 'Sibling folder and file labels align');

  const tabStyle = await page.locator('.active-pane').evaluate(n => ({
    fill: getComputedStyle(n.querySelector('.pane-tab.selected')).backgroundColor,
    background: getComputedStyle(n).backgroundColor,
    shadow: getComputedStyle(n.querySelector('.tab-strip')).boxShadow,
    separator: getComputedStyle(n.querySelector('.pane-tab')).borderRightWidth,
  }));
  assert.notEqual(tabStyle.fill, tabStyle.background);
  assert.equal(tabStyle.shadow, 'none', 'No accent stripe over the tab bar');
  assert.equal(tabStyle.separator, '1px');
  assert.equal(await page.locator('#breadcrumb').isVisible(), true);
  await page.locator('#file-nav a[href="#art"]').click();
  await page.locator('#file-nav a[href="#interests"]').click();
  assert.equal(await page.locator('#tabs .preview-tab').count(), 1);
  assert.equal(await page.locator('#tabs .pane-tab').count(), 2);
  await page.locator('#tabs .preview-tab').dblclick();
  assert.equal(await page.locator('#tabs .preview-tab').count(), 0);
  await quickOpen('rdme');
  assert.equal(new URL(page.url()).hash, '#home');
  await page.keyboard.press('Control+p');
  assert.equal(await page.locator('[data-open-route]').first().getAttribute('data-open-route'), 'home');
  await page.locator('#file-query').fill('rdme');
  assert.ok(await page.locator('#file-results mark').count() > 0);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#content').evaluate(n => n === document.activeElement), true);

  const first = page.locator('.editor-pane').first();
  const firstId = await first.getAttribute('data-pane-id');
  await first.locator('.content').evaluate(n => { n.scrollTop = 250; });
  const oldScroll = await first.locator('.content').evaluate(n => n.scrollTop);
  await split('right');
  assert.equal(await page.locator('.editor-pane').count(), 2);
  const secondId = await page.locator('.active-pane').getAttribute('data-pane-id');
  await quickOpen('art.md');
  assert.equal(await first.locator('.content').getAttribute('data-route'), 'home');
  assert.equal(await first.locator('.content').evaluate(n => n.scrollTop), oldScroll);
  const historyLength = await page.evaluate(() => history.length);
  await first.locator('.editor-path').click({ position: { x: 30, y: 16 } });
  assert.equal(new URL(page.url()).hash, '#home');
  assert.equal(await page.evaluate(() => history.length), historyLength, 'Pane activation replaces rather than pushes URL history');
  const second = page.locator(`[data-pane-id="${secondId}"]`);
  await second.locator('[data-role="buffer-search-btn"]').click();
  await second.locator('[data-find-query]').fill('color');
  assert.ok(await second.locator('mark[data-search-match]').count() > 0);
  assert.equal(await first.locator('mark[data-search-match]').count(), 0);
  const beforeMatch = await second.locator('.match-count').textContent();
  await page.keyboard.press('Enter');
  assert.notEqual(await second.locator('.match-count').textContent(), beforeMatch);
  await second.getByRole('button', { name: 'Use regular expression', exact: true }).click();
  await second.locator('[data-find-query]').fill('[');
  assert.equal(await second.locator('[data-find-query]').getAttribute('aria-invalid'), 'true');
  assert.match(await second.locator('.match-count').textContent(), /Invalid/);
  await second.getByRole('button', { name: 'Use regular expression', exact: true }).click();
  await second.locator('[data-find-query]').fill('Clip Studio Paint');
  assert.ok(await second.locator('mark[data-search-match]').count() > 0);
  await page.keyboard.press('Escape');
  assert.equal(await second.locator('.buffer-search').isVisible(), false);
  assert.equal(await second.locator('.content').evaluate(n => n === document.activeElement), true);
  await page.keyboard.press('Control+f');
  assert.equal(await second.locator('[data-find-query]').inputValue(), 'Clip Studio Paint');
  await page.keyboard.press('Escape');

  await page.locator('#outline-btn').click();
  await page.locator('#outline-query').fill('themes');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#outline-picker').evaluate(n => n.open), false);
  assert.match(await page.evaluate(() => document.activeElement.textContent), /themes/i);
  await split('down');
  assert.equal(await page.locator('.editor-pane').count(), 3);
  assert.equal(await page.locator('.pane-group.vertical').count(), 1);
  const thirdId = await page.locator('.active-pane').getAttribute('data-pane-id');
  await quickOpen('projects.md');
  await page.locator('#content [data-filter="Apps"]').click();
  assert.equal(await page.locator('#content .project-row').count(), projects.filter(p => p.category === 'Apps').length);
  assert.equal(await second.locator('.content').getAttribute('data-route'), 'art');
  await page.locator('#editor-maximize-btn').click();
  assert.equal(await first.isVisible(), false);
  assert.equal(await second.isVisible(), false);
  assert.equal(await page.locator('#terminal').isVisible(), false);
  await page.locator('#editor-maximize-btn').click();
  assert.equal(await first.isVisible(), true);
  const separator = page.locator('.pane-group.horizontal > .pane-separator').first();
  await separator.focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await separator.getAttribute('aria-valuenow'), '55');
  const box = await separator.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + 60);
  await page.mouse.down(); await page.mouse.move(box.x - 50, box.y + 60); await page.mouse.up();
  assert.ok(Number(await separator.getAttribute('aria-valuenow')) < 55);
  await separator.dblclick();
  assert.equal(await separator.getAttribute('aria-valuenow'), '50');

  // A real drag moves an item into the receiving pane without changing its neighbor.
  await first.locator('[data-tab-route="home"]').dragTo(second.locator('.tabs'));
  assert.equal(await first.locator('[data-tab-route="home"]').count(), 0);
  assert.equal(await second.locator('[data-tab-route="home"]').count(), 1);
  assert.equal(await page.locator('.active-pane').getAttribute('data-pane-id'), secondId);
  await page.locator('.statusbar [data-terminal-toggle]').click();
  await page.locator('#terminal-input').fill('about');
  await page.keyboard.press('Enter');
  assert.equal(await second.locator('.content').getAttribute('data-route'), 'about');
  assert.equal(await page.locator(`[data-pane-id="${thirdId}"] .content`).getAttribute('data-route'), 'projects');
  await page.locator('.statusbar [data-terminal-toggle]').click();

  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('#pane-switcher').isVisible(), true);
  assert.equal(await page.locator('.editor-pane:visible').count(), 1);
  await page.locator('#pane-switcher').selectOption(thirdId);
  assert.equal(new URL(page.url()).hash, '#projects');
  assert.equal(await page.locator('#content .project-row').count(), projects.filter(p => p.category === 'Apps').length);
  assert.equal(await page.locator('.editor-pane').count(), 3);
  for (const theme of themes) {
    await page.locator('#status-theme').click();
    await page.locator(`[data-theme-id="${theme.id}"]`).click();
    await page.keyboard.press('Escape');
    await page.locator('#buffer-search-btn').click();
    await page.locator('.active-pane [data-find-query]').fill('Apps');
    assert.deepEqual(await page.evaluate(contrastFailures), [], `${theme.id} mobile pane and search contrast`);
    if (artifactDir) await page.screenshot({ path: `${artifactDir}/panes-mobile-${theme.id}.png` });
    await page.setViewportSize({ width: 1440, height: 1000 });
    assert.equal(await page.locator('.editor-pane:visible').count(), 3);
    for (const content of await page.locator('.editor-pane .content').all()) assert.equal(await content.evaluate(n => n.scrollWidth <= n.clientWidth), true, `${theme.id} split content fits`);
    if (artifactDir) await page.screenshot({ path: `${artifactDir}/panes-desktop-${theme.id}.png` });
    await page.locator('.active-pane [data-close-search]').click();
    await page.setViewportSize({ width: 390, height: 844 });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  const ids = await page.locator('[id]').evaluateAll(nodes => nodes.map(n => n.id));
  assert.equal(new Set(ids).size, ids.length, 'Split pages do not duplicate DOM IDs');
  await closePane();
  assert.equal(await page.locator('.editor-pane').count(), 2);
  await closePane();
  assert.equal(await page.locator('.editor-pane').count(), 1);
  while (await page.locator('#tabs [data-close-tab]').count()) await page.locator('#tabs [data-close-tab]').first().click();
  assert.equal(await page.locator('.empty-pane').isVisible(), true);
  await quickOpen('about');
  assert.equal(await page.locator('#content h1').count(), 1);
  await quickOpen('art');
  await page.goBack();
  assert.equal(await page.locator('#content').getAttribute('data-route'), 'about');
  await page.goForward();
  assert.equal(await page.locator('#content').getAttribute('data-route'), 'art');
  await page.goBack();
  assert.equal(await page.locator('#history-forward').isEnabled(), true, 'Browser history restores the pane history position');
  await page.goForward();
  await page.keyboard.press('Control+p');
  await page.locator('#file-query').fill('zzzzzzzz');
  await page.keyboard.press('Control+Enter');
  assert.equal(await page.locator('.editor-pane').count(), 1, 'No split without a selected result');
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+p');
  await page.locator('#file-query').fill('about.md');
  await page.locator('#file-open-split').click();
  assert.equal(await page.locator('.editor-pane').count(), 2);
  assert.equal(await page.locator('#tabs .pane-tab').count(), 1, 'Open in split adds only the requested item');
  const activeTab = page.locator('#tabs .tab').first();
  await activeTab.focus();
  await page.keyboard.press('Shift+F10');
  assert.equal(await page.getByRole('menuitem', { name: 'Move to pane 1' }).isVisible(), true);
  await page.keyboard.press('Escape');
  assert.equal(await activeTab.evaluate(n => n === document.activeElement), true);
  await page.keyboard.press('Shift+F10');
  await page.getByRole('menuitem', { name: 'Move to pane 1' }).click();
  assert.equal(await page.locator('.editor-pane').count(), 1);
  await page.keyboard.press('Control+k');
  await page.keyboard.press('ArrowUp');
  assert.equal(await page.locator('.editor-pane').count(), 2);
  await page.keyboard.press('Shift+Escape');
  assert.equal(await page.locator('.editor-pane:visible').count(), 1);
  await page.keyboard.press('Shift+Escape');
  assert.equal(await page.locator('.editor-pane:visible').count(), 2);
  await closePane();
  await page.keyboard.press('Control+f');
  await page.locator('.active-pane [data-find-query]').fill('person');
  await page.setViewportSize({ width: 320, height: 568 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await page.locator('.active-pane').evaluate(n => n.scrollWidth <= n.clientWidth), true);
  await page.keyboard.press('Escape');
  assert.ok(firstId);
  await checkTabStrip(page, origin);
  page.setDefaultTimeout(30000);
}

async function checkTabStrip(page, origin) {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${origin}/#about`);
  await page.reload();
  const tabs = page.locator('#tabs');
  const box = await tabs.boundingBox();
  await tabs.dblclick({ position: { x: box.width - 20, y: 15 } });
  assert.equal(await page.locator('.scratch-buffer').count(), 1, 'Empty tab-strip double-click creates a file');
  assert.equal(await page.locator('#tabs .pane-tab').count(), 2);
  assert.equal(await page.locator('.scratch-buffer').evaluate(n => n === document.activeElement), true);
  await page.locator('.scratch-buffer').fill('temporary notes');
  await page.locator('#tabs a[href="#about"]').click();
  await page.locator('#tabs a[href^="#untitled/"]').click();
  assert.equal(await page.locator('.scratch-buffer').inputValue(), 'temporary notes');
  await page.locator('#tabs a[href^="#untitled/"]').dblclick();
  assert.equal(await page.locator('#tabs .pane-tab').count(), 2, 'Double-clicking a tab keeps it without creating a file');
  await page.locator('#editor-split-btn').click();
  assert.equal(await page.locator('#editor-split-btn').isVisible(), true, 'Pane menu keeps its controls visible');
  await page.getByRole('menuitem', { name: 'Split right', exact: true }).click();
  assert.equal(await page.locator('.editor-pane .tab-actions:visible').count(), 1);
  const inactive = page.locator('.editor-pane:not(.active-pane)');
  assert.equal(await inactive.locator('.tab-actions').isVisible(), false);
  await page.locator('.active-pane .scratch-buffer').fill('shared scratch text');
  assert.equal(await inactive.locator('.scratch-buffer').inputValue(), 'shared scratch text');
  await page.locator('#status-theme').focus();
  assert.equal(await page.locator('.editor-pane .tab-actions:visible').count(), 0, 'Controls hide when focus leaves editor panes');
  await inactive.locator('.scratch-buffer').focus();
  assert.equal(await page.locator('.editor-pane .tab-actions:visible').count(), 1);
  const downloadEvent = page.waitForEvent('download');
  await page.locator('.active-pane [data-download-buffer]').click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(), 'untitled.txt');
  await page.locator('.active-pane [data-role="new-item-btn"]').click();
  await page.getByRole('menuitem', { name: 'New File', exact: true }).click();
  assert.equal(await page.locator('.active-pane .scratch-buffer').inputValue(), '');
  await page.locator('.active-pane [data-role="new-item-btn"]').click();
  await page.getByRole('menuitem', { name: 'Open File', exact: true }).click();
  assert.equal(await page.locator('#file-picker').evaluate(n => n.open), true);
  await page.keyboard.press('Escape');
  while (await page.locator('#tabs [data-close-tab]').count()) await page.locator('#tabs [data-close-tab]').first().click();
  while (await page.locator('#tabs [data-close-tab]').count()) await page.locator('#tabs [data-close-tab]').first().click();
  await page.locator('.active-pane .content').focus();
  assert.equal(await page.locator('#editor-split-btn').isDisabled(), true, 'An empty pane cannot split an item');
  await page.locator('.empty-pane').dblclick({ position: { x: 10, y: 10 } });
  assert.equal(await page.locator('.active-pane .scratch-buffer').count(), 1, 'Empty pane double-click creates a file');
  await page.locator('.active-pane .scratch-buffer').fill('hello notes');
  await page.keyboard.press('Control+f');
  await page.locator('.active-pane [data-find-query]').fill('notes');
  assert.equal(await page.locator('.active-pane .match-count').textContent(), '1 / 1');
  assert.deepEqual(await page.locator('.scratch-buffer').evaluate(n => [n.selectionStart, n.selectionEnd]), [6, 11]);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.scratch-buffer').evaluate(n => n === document.activeElement), true);
  const downloadNotes = page.waitForEvent('download');
  await page.locator('.active-pane [data-download-buffer]').click();
  await downloadNotes;
}
